"""Seed the app catalog: ready-made integrations with brand icons.

Every row is a *template*: installing it copies `config_template` /
`actions_template` into a normal tenant `tools` row, so nothing here runs by
itself and no credential ships with the product.

`icon` is `<set>:<name>`; the panel resolves it (`components/app-icons.tsx`)
and falls back to a coloured monogram for unknown entries.
"""

