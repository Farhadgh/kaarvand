"""Alembic environment (async, group aware)."""

from __future__ import annotations

import asyncio
import os
from logging.config import fileConfig

from alembic import context
from sqlalchemy import pool
from sqlalchemy.engine import Connection
from sqlalchemy.ext.asyncio import async_engine_from_config

from app.core.config import get_settings
from app.db.base import GROUPS, Base

config = context.config

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

settings = get_settings()
config.set_main_option("sqlalchemy.url", settings.effective_migration_url)

target_metadata = Base.metadata


def _allowed_tables() -> set[str] | None:
    """ALEMBIC_GROUPS=core,providers limits autogenerate to those tables."""
    raw = os.getenv("ALEMBIC_GROUPS", "").strip()
    if not raw:
        return None
    allowed: set[str] = set()
    for name in raw.split(","):
        key = name.strip()
        if key not in GROUPS:
            raise SystemExit(f"unknown ALEMBIC_GROUPS entry: {key!r}")
        allowed.update(GROUPS[key])
    return allowed


def include_object(obj, name, type_, reflected, compare_to):  # noqa: ANN001
    allowed = _allowed_tables()
    if allowed is None:
        return True
    if type_ == "table":
        return name in allowed
    parent = getattr(obj, "table", None)
    if parent is not None:
        return parent.name in allowed
    return True


def render_item(type_, obj, autogen_context):  # noqa: ANN001
    """Render pgvector columns nicely in future autogenerated migrations."""
    if type_ == "type" and obj.__class__.__module__.startswith("pgvector"):
        autogen_context.imports.add("from pgvector.sqlalchemy import Vector")
        return f"Vector({obj.dim})"
    return False


def run_migrations_offline() -> None:
    context.configure(
        url=settings.effective_migration_url,
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
        include_object=include_object,
        render_item=render_item,
        compare_type=True,
        compare_server_default=True,
    )
    with context.begin_transaction():
        context.run_migrations()


def do_run_migrations(connection: Connection) -> None:
    context.configure(
        connection=connection,
        target_metadata=target_metadata,
        include_object=include_object,
        render_item=render_item,
        compare_type=True,
        compare_server_default=True,
    )
    with context.begin_transaction():
        context.run_migrations()


async def run_async_migrations() -> None:
    connectable = async_engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )
    async with connectable.connect() as connection:
        await connection.run_sync(do_run_migrations)
    await connectable.dispose()


def run_migrations_online() -> None:
    asyncio.run(run_async_migrations())


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
