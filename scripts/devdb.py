"""Local development database bootstrap.

Starts the embedded PostgreSQL server (``pgserver``) used for development,
creates the non-superuser application role (so RLS is really enforced), creates
the ``openbot`` / ``openbot_test`` databases and writes ``services/api/.env.local``.

Usage (from repo root):
    python scripts/devdb.py            # start + configure
    python scripts/devdb.py --info     # print current connection info
"""

from __future__ import annotations

import argparse
import asyncio
import base64
import os
import secrets
import sys
from pathlib import Path
from urllib.parse import urlparse, urlunparse

import asyncpg
import pgserver

ROOT = Path(__file__).resolve().parent.parent
PGDATA = ROOT / ".pgdata"
ENV_LOCAL = ROOT / "services" / "api" / ".env.local"

APP_ROLE = "openbot_app"
APP_PASSWORD = "openbot"
DATABASES = ("openbot", "openbot_test")

ROLE_SQL = f"""
do $$
begin
    if not exists (select 1 from pg_roles where rolname = '{APP_ROLE}') then
        create role {APP_ROLE} login password '{APP_PASSWORD}'
            nosuperuser nocreatedb nocreaterole;
    end if;
end $$;
"""

GRANT_SQL = f"""
grant usage on schema public to {APP_ROLE};
grant select, insert, update, delete on all tables in schema public to {APP_ROLE};
grant usage, select on all sequences in schema public to {APP_ROLE};
grant execute on all functions in schema public to {APP_ROLE};
alter default privileges for role postgres in schema public
    grant select, insert, update, delete on tables to {APP_ROLE};
alter default privileges for role postgres in schema public
    grant usage, select on sequences to {APP_ROLE};
alter default privileges for role postgres in schema public
    grant execute on functions to {APP_ROLE};
"""


def _with_db(uri: str, dbname: str, user: str | None = None, password: str | None = None) -> str:
    parsed = urlparse(uri)
    netloc = parsed.netloc
    if user is not None:
        host = parsed.hostname or "127.0.0.1"
        port = parsed.port or 5432
        netloc = f"{user}:{password or ''}@{host}:{port}"
    return urlunparse(parsed._replace(netloc=netloc, path=f"/{dbname}"))


def _read_env(path: Path) -> dict[str, str]:
    data: dict[str, str] = {}
    if not path.exists():
        return data
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        data[key.strip()] = value.strip()
    return data


def _write_env(path: Path, values: dict[str, str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# generated by scripts/devdb.py - local development only",
        "# safe to regenerate: secrets are preserved if already present",
        "",
    ]
    for key, value in values.items():
        lines.append(f"{key}={value}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


async def _ensure_databases(base_uri: str) -> None:
    conn = await asyncpg.connect(base_uri)
    try:
        await conn.execute(ROLE_SQL)
        for db in DATABASES:
            exists = await conn.fetchval("select 1 from pg_database where datname = $1", db)
            if not exists:
                await conn.execute(f'create database "{db}"')
    finally:
        await conn.close()

    for db in DATABASES:
        c = await asyncpg.connect(_with_db(base_uri, db))
        try:
            await c.execute(GRANT_SQL)
        finally:
            await c.close()


def main() -> int:
    parser = argparse.ArgumentParser(description="local postgres bootstrap")
    parser.add_argument("--info", action="store_true", help="only print connection info")
    args = parser.parse_args()

    if not PGDATA.exists() and args.info:
        print("no local database yet; run: python scripts/devdb.py", file=sys.stderr)
        return 1

    server = pgserver.get_server(PGDATA, cleanup_mode=None)
    base_uri = server.get_uri()

    if not args.info:
        asyncio.run(_ensure_databases(base_uri))

    app_uri = _with_db(base_uri, "openbot", APP_ROLE, APP_PASSWORD)
    test_uri = _with_db(base_uri, "openbot_test", APP_ROLE, APP_PASSWORD)
    migration_uri = _with_db(base_uri, "openbot", "postgres", "")

    if not args.info:
        existing = _read_env(ENV_LOCAL)
        values = {
            "APP_ENV": "dev",
            "APP_DEBUG": "true",
            "APP_DATABASE_URL": app_uri.replace("postgresql://", "postgresql+asyncpg://"),
            "APP_MIGRATION_DATABASE_URL": migration_uri.replace(
                "postgresql://", "postgresql+asyncpg://"
            ),
            "APP_JWT_SECRET": existing.get("APP_JWT_SECRET") or secrets.token_urlsafe(48),
            "APP_MASTER_KEY": existing.get("APP_MASTER_KEY")
            or base64.urlsafe_b64encode(os.urandom(32)).decode(),
            "APP_FREE_MODE": "true",
            "APP_BILLING_ENABLED": "false",
            "APP_PAYMENT_GATEWAY": "noop",
            "APP_DEFAULT_LOCALE": "fa",
            "APP_DEFAULT_TIMEZONE": "Asia/Tehran",
            "APP_DEFAULT_CALENDAR": "jalali",
            "APP_DEFAULT_CURRENCY": "IRR",
            "APP_DEFAULT_DIGITS": "fa",
        }
        _write_env(ENV_LOCAL, values)
        print(f"wrote {ENV_LOCAL}")

    print(f"postgres   : {base_uri}")
    print(f"app url    : {app_uri}")
    print(f"test url   : {test_uri}")
    print(f"migration  : {migration_uri}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
